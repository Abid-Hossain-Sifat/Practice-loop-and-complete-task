/*For of loop
For of loop is used to iterate over elements of an array or any iterable object. It executes a block of code for each element.

Syntax:-
for (declare item of iterable){
console.run
}
*/

const numbers =[12, 65, 89, 65, 78, 69, 54];
for (const number of numbers){
    console.log (number);
}



